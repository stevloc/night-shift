const DICTS: Record<Lang, Record<Key, string>> = { en, es };
export const LOCALES: Record<Lang, string> = { en: "en-US", es: "es-US" };
export const LANG_NAMES: Record<Lang, string> = { en: "English", es: "Español" };

export type Params = Record<string, string | number>;

export function makeT(lang: Lang) {
  const dict = DICTS[lang];
  const locale = LOCALES[lang];
  const plural = new Intl.PluralRules(locale);

  const fill = (text: string, params?: Params) =>
    text.replace(/\{(\w+)\}/g, (_, name) => String(params?.[name] ?? `{${name}}`));
  /** Translate a key; falls back to English, then to the key itself. */
  const t = (key: Key, params?: Params) => fill(dict[key] ?? en[key] ?? String(key), params);
  /** Plural-aware: uses `${base}_one` / `${base}_other`. */
  const tp = (base: string, count: number, params?: Params) => {
    const key = (`${base}_${plural.select(count)}` in en ? `${base}_${plural.select(count)}` : `${base}_other`) as Key;
    return t(key, { count: num(count), ...params });
  };

  const moneyFmt = new Intl.NumberFormat(locale, { style: "currency", currency: "USD" });
  const numFmt = new Intl.NumberFormat(locale, { maximumFractionDigits: 2 });
  const pctFmt = new Intl.NumberFormat(locale, { style: "percent", maximumFractionDigits: 1 });
  const timeFmt = new Intl.DateTimeFormat(locale, { hour: "numeric", minute: "2-digit" });
  const listFmt = new Intl.ListFormat(locale, { style: "long", type: "conjunction" });

  /** Money with a real minus sign; `signed` adds "+" to positive values. */
  function money(n: number, signed = false) {
    const text = moneyFmt.format(Math.abs(n));
    if (n < -0.004) return `−\u2060${text}`;  // word joiner: never wrap between − and $
    return signed && n > 0.004 ? `+${text}` : text;
  }
  const unitFmt = new Intl.NumberFormat(locale, { style: "currency", currency: "USD", maximumFractionDigits: 4 });
  /** Per-unit costs: under $1 keep up to 4 decimals ($0.0735 per sheet). */
  const unitMoney = (n: number) => (Math.abs(n) < 1 ? unitFmt.format(n) : moneyFmt.format(n));
  const wholeFmt = new Intl.NumberFormat(locale, { style: "currency", currency: "USD", maximumFractionDigits: 0 });
  /** Rounded monthly figure for scenarios: "~$169" (the exact value is in the source popover). */
  const approx = (n: number) => `~${n < 0 ? "−\u2060" : ""}${wholeFmt.format(Math.abs(n))}`;
  function num(n: number) { return numFmt.format(n); }
  /** pct(0.12) -> "12%";  pctPoints(29.3) -> "29.3%" */
  const pct = (fraction: number) => pctFmt.format(Math.abs(fraction));
  const pctPoints = (points: number) => pctFmt.format(points / 100);
  const time = (iso: string) => timeFmt.format(new Date(iso));
  const dayFmt = new Intl.DateTimeFormat(locale, { dateStyle: "medium" });
  /** "2026-11-06" -> "Nov 6, 2026"; other text is returned unchanged. */
  const day = (text: string) => (/^\d{4}-\d{2}-\d{2}$/.test(text) ? dayFmt.format(new Date(`${text}T12:00:00`)) : text);
  const list = (items: string[]) => listFmt.format(items);
  const name = (names: Names) => names[lang] ?? names.en;
  /** Unit label, plural for counts other than 1 (500 sheets, 50 unidades). */
  const PLURALS: Record<Lang, Record<string, string>> = {
    en: { sheet: "sheets", bowl: "bowls" }, es: { each: "unidades", sheet: "hojas", bowl: "tazones" },
  };
  const unit = (u: string, count = 1) => (count !== 1 && PLURALS[lang][u]) || t(`unit_${u}` as Key);
  /** Like t(), but params may be React nodes (e.g. a number with a "source" popover). */
  function rich(key: Key, params: Record<string, ReactNode>): ReactNode[] {
    const text = dict[key] ?? en[key] ?? String(key);
    return text.split(/(\{\w+\})/).map((part, i) => {
      const m = part.match(/^\{(\w+)\}$/);
      return m && m[1] in params ? <Fragment key={i}>{params[m[1]]}</Fragment> : part;
    });
  }

  return { t, tp, rich, money, approx, unitMoney, num, pct, pctPoints, time, day, list, name, unit, locale, lang };
}

export type I18n = ReturnType<typeof makeT>;
