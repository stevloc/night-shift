"""Generate supabase/migrations/..._seed_demo_template.sql from demo-data/.

SQL functions can't read files, so the demo dataset is loaded once into a "template" restaurant;
create_demo_restaurant(user_id) copies it for each new user.

    python scripts/build_seed_sql.py      (re-run whenever demo-data/ changes)
"""

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from data import DEFAULT_SETTINGS, DEMO, DISHES, INGREDIENTS, PREVIOUS_INVOICES, RESTAURANT_NAME  # noqa: E402

TEMPLATE_ID = "00000000-0000-4000-8000-00000000d3a0"
OUT = ROOT / "supabase" / "migrations" / "20261107000003_seed_demo_template.sql"


def lit(value):
    """SQL literal (strings and JSON are escaped; numbers and NULL as-is)."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (dict, list)):
        return lit(json.dumps(value, ensure_ascii=False)) + "::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def rows(name):
    with open(DEMO / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def values(items):
    return ",\n".join("  (" + ", ".join(lit(v) for v in item) + ")" for item in items)


def main():
    t = lit(TEMPLATE_ID)
    out = [
        "-- GENERATED by scripts/build_seed_sql.py from demo-data/ (all fictional). Do not edit by hand.",
        "-- The template restaurant that create_demo_restaurant(user_id) copies for each new user.",
        "",
        f"delete from public.restaurants where id = {t};",
        "",
        "insert into public.restaurants (id, owner_user_id, name, settings, is_template) values",
        f"  ({t}, null, {lit(RESTAURANT_NAME)}, {lit(DEFAULT_SETTINGS)}, true);",
        "",
        "insert into public.ingredients (restaurant_id, ingredient_key, name, invoice_alias, pack_desc, pack_size, pack_unit,",
        "  pack_price, yield_pct, baseline_pack_size, baseline_pack_unit, baseline_pack_price, source) values",
    ]
    ing = []
    for key, i in INGREDIENTS.items():
        supplier, number, date = PREVIOUS_INVOICES[key]
        source = {"kind": "previous", "supplier": supplier, "invoice_no": number, "date": date}
        ing.append((TEMPLATE_ID, key, i["name"], i["alias"], i["pack_desc"], i["pack_size"], i["pack_unit"],
                    i["pack_price"], i["yield_pct"], i["pack_size"], i["pack_unit"], i["pack_price"], source))
    out += [values(ing) + ";", ""]

    out.append("insert into public.menu_items (restaurant_id, item_key, name, in_store_price, doordash_price) values")
    out += [values([(TEMPLATE_ID, k, d["name"], d["prices"]["in_store"], d["prices"]["doordash"])
                    for k, d in DISHES.items()]) + ";", ""]

    out.append("insert into public.recipes (restaurant_id, item_key, ingredient_key, qty, unit) values")
    out += [values([(TEMPLATE_ID, k, ik, qty, unit) for k, d in DISHES.items()
                    for ik, (qty, unit) in d["recipe"].items()]) + ";", ""]

    out.append("insert into public.price_history (restaurant_id, ingredient_key, observed_on, pack_price, pack_size, pack_unit, source) values")
    history = []
    for r in rows("price_history.csv"):
        i = INGREDIENTS[r["ingredient_id"]]
        history.append((TEMPLATE_ID, r["ingredient_id"], r["date"], float(r["pack_price"]), i["pack_size"], i["pack_unit"],
                        {"kind": "previous", "supplier": "Price history:", "invoice_no": "delivery", "date": r["date"]}))
    out += [values(history) + ";", ""]

    by_name = {d["name"]["en"]: k for k, d in DISHES.items()}
    out.append("insert into public.orders_daily (restaurant_id, item_key, day, orders) values")
    out += [values([(TEMPLATE_ID, by_name[r["dish"]], r["date"], int(r["orders"]))
                    for r in rows("doordash_orders.csv")]) + ";", ""]

    OUT.write_text("\n".join(out))
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(ing)} ingredients, {len(DISHES)} dishes, "
          f"{len(history)} price rows, {len(rows('doordash_orders.csv'))} order rows)")


if __name__ == "__main__":
    main()
